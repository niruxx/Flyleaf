const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const JSZip = require('jszip');
const { parse } = require('node-html-parser');
const config = require('../server/config');
const { rendition } = require('../server/kepub');
const { koboLocation, koboCFI } = require('../server/kobo-position');

test('ordinary EPUB gets a stable Kobo rendition and bidirectional original position map', async t => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'flyleaf-kepub-'));
  const previousCache = config.cacheDir;
  config.cacheDir = path.join(dir, 'cache');
  t.after(async () => { config.cacheDir = previousCache; await fs.rm(dir, { recursive: true, force: true }); });
  const zip = new JSZip();
  zip.file('META-INF/container.xml', '<container><rootfiles><rootfile full-path="OPS/package.opf"/></rootfiles></container>');
  zip.file('OPS/package.opf', '<package><metadata/><manifest><item id="c" href="c.xhtml" media-type="application/xhtml+xml"/></manifest><spine><itemref idref="c"/></spine></package>');
  const chapter = '<html xmlns="http://www.w3.org/1999/xhtml"><head><title>Chapter</title><meta name="test" content="value"/></head><body><p>First sentence. Second &amp; 😀 sentence!</p><p>A <em>nested</em> paragraph.<br/><img src="cover.jpg"/></p></body></html>';
  zip.file('OPS/c.xhtml', chapter);
  zip.file('mimetype', 'application/epub+zip');
  const file = path.join(dir, 'book.epub');
  const original = await zip.generateAsync({ type: 'nodebuffer' });
  await fs.writeFile(file, original);
  const book = { path: file, format: 'epub' };
  const [first, concurrent] = await Promise.all([rendition(book), rendition(book)]);
  assert.equal(first.key, concurrent.key);
  assert.ok(first.spans.length >= 4);
  assert.deepEqual(await fs.readFile(file), original, 'original EPUB remains byte-for-byte identical');
  const converted = await JSZip.loadAsync(await fs.readFile(first.file));
  const bytes = await fs.readFile(first.file);
  assert.equal(bytes.readUInt16LE(8), 0, 'mimetype is stored without compression');
  assert.equal(bytes.subarray(30, 30 + bytes.readUInt16LE(26)).toString(), 'mimetype', 'mimetype is the first ZIP member');
  const dom = parse(await converted.file('OPS/c.xhtml').async('string'));
  assert.ok(dom.querySelector('#book-inner'));
  assert.match(await converted.file('OPS/c.xhtml').async('string'), /<br\s*\/>/);
  assert.match(await converted.file('OPS/c.xhtml').async('string'), /<img[^>]+\/>/);
  assert.equal(dom.querySelector('body').text, parse(chapter).querySelector('body').text);
  assert.equal(dom.querySelectorAll('.koboSpan').length, first.spans.length);
  const location = await koboLocation(book, 'epubcfi(/6/2!/4/2/1:21)');
  assert.equal(location.Type, 'KoboSpan');
  assert.equal(location.Source, 'OPS/c.xhtml');
  assert.ok(dom.querySelectorAll('[id]').some(n => n.getAttribute('id') === location.Value));
  assert.equal(await koboCFI(book, location), 'epubcfi(/6/2!/4/2/1:16)');
  assert.equal((await rendition(book)).key, first.key, 'cache identity is stable');
  await fs.writeFile(file, Buffer.from(await zip.generateAsync({ type: 'nodebuffer', comment: 'updated edition' })));
  assert.notEqual((await rendition(book)).key, first.key, 'changed book gets a new rendition');
  zip.file('OPS/c.xhtml', '<html><head><title>Kobo</title></head><body><div id="book-columns"><div id="book-inner"><p><span class="koboSpan" id="kobo.9.1">Existing span</span> New text.</p></div></div></body></html>');
  await fs.writeFile(file, await zip.generateAsync({ type: 'nodebuffer' }));
  const existing = await rendition(book);
  const kept = parse(await (await JSZip.loadAsync(await fs.readFile(existing.file))).file('OPS/c.xhtml').async('string'));
  assert.equal(kept.querySelectorAll('#book-columns').length, 1);
  assert.equal(kept.querySelectorAll('[id="kobo.9.1"]').length, 1);
  assert.equal(await koboCFI(book, { Source: 'OPS/c.xhtml', Type: 'KoboSpan', Value: 'kobo.9.1' }), 'epubcfi(/6/2!/4/2/2/2/2/1:0)');
});
