const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const JSZip = require('jszip');
const { epubXPointer, epubFromXPointer } = require('../server/kosync-position');
const { koboLocation, koboCFI } = require('../server/kobo-position');

test('EPUB CFIs convert arbitrary chapter positions without an observed anchor', async t => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'flyleaf-kosync-'));
  const config = require('../server/config'), previousCache = config.cacheDir;
  config.cacheDir = path.join(dir, 'cache');
  t.after(async () => { config.cacheDir = previousCache; await fs.rm(dir, { recursive: true, force: true }); });
  const zip = new JSZip();
  zip.file('META-INF/container.xml', '<container><rootfiles><rootfile full-path="OPS/package.opf"/></rootfiles></container>');
  zip.file('OPS/package.opf', '<package><metadata/><manifest><item id="a" href="a.xhtml" media-type="application/xhtml+xml"/><item id="b" href="Text/b%20chapter.xhtml" media-type="application/xhtml+xml"/></manifest><spine><itemref idref="a"/><itemref idref="b" linear="no"/></spine></package>');
  zip.file('OPS/a.xhtml', '<html><head><title>A</title></head><body>\n<p>First chapter.</p><p id="a,b">\n<em>Nested</em> text  with\nspaces.</p><p style="white-space:pre-wrap">Keep  spacing</p></body></html>');
  zip.file('OPS/Text/b chapter.xhtml', '<html><head><title>B</title></head><body><div><h1>Title</h1><p id="p">Hello &amp; 😀 world <em>emphasis</em> tail.</p><p>Second paragraph</p><pre>preserved  spaces</pre><p><span id="kobo.1.1">Kobo text</span></p></div></body></html>');
  const file = path.join(dir, 'book.epub');
  await fs.writeFile(file, await zip.generateAsync({ type: 'nodebuffer' }));
  const book = { format: 'epub', path: file };
  const convert = cfi => epubXPointer(book, `epubcfi(${cfi})`);
  assert.equal(await convert('/6/4!/4/2/4[p]/1:11'), '/body/DocFragment[2]/body/div[1]/p[1]/text()[1].10', 'entity decoding and UTF-16 to UTF-32 offsets');
  assert.equal(await epubFromXPointer(book, '/body/DocFragment[2]/body/div[1]/p[1]/text()[1].10'), 'epubcfi(/6/4!/4/2/4/1:11)');
  assert.equal(await epubFromXPointer(book, '/body/DocFragment[2]/body/div/p/text().8'), 'epubcfi(/6/4!/4/2/4/1:8)');
  assert.equal(await epubFromXPointer(book, '/body/DocFragment[99]/body/p/text().0'), null);
  assert.equal(await convert('/6/4!/4/2/4/2/1:3'), '/body/DocFragment[2]/body/div[1]/p[1]/em[1]/text()[1].3');
  assert.equal(await convert('/6/4!/4/2/4/3:2'), '/body/DocFragment[2]/body/div[1]/p[1]/text()[2].2');
  assert.equal(await convert('/6/4!/4/2/6/1:4'), '/body/DocFragment[2]/body/div[1]/p[2]/text()[1].4', 'element indexes count siblings by tag');
  assert.equal(await convert('/6/4!/4/2/6,/1:4,/1:8'), '/body/DocFragment[2]/body/div[1]/p[2]/text()[1].4', 'range uses its start');
  assert.equal(await convert('/6/4!/4/2/8/1:11'), '/body/DocFragment[2]/body/div[1]/pre[1]/text()[1].11');
  assert.equal(await convert('/6/2!/4/2/1:0'), '/body/DocFragment[1]/body/p[1]/text()[1].0');
  assert.equal(await convert('/6/2!/4/4[a^,b]/3:13'), '/body/DocFragment[1]/body/p[2]/text()[1].12', 'dropped leading block whitespace does not shift native text indexes');
  assert.equal(await convert('/6/2!/4/6/1:4'), null, 'publisher whitespace overrides use fallback');
  assert.equal(await convert('/6/4!/4/2/4/1:9'), null, 'reject offsets bisecting a surrogate pair');
  for (const cfi of ['/6/8!/4/2/1:0', '/6/4!/4/2/4[wrong]/1:0', '/6/4!/4/2/6/1:9999', '/6/4!/4/2/99:0']) assert.equal(await convert(cfi), null);
  assert.equal(await epubXPointer(book, 'not a CFI'), null);
  assert.equal(await epubXPointer({ ...book, format: 'mobi' }, 'epubcfi(/6/2!/4/2/1:0)'), null);
  const location = await koboLocation(book, 'epubcfi(/6/4!/4/2/10/2/1:4)');
  assert.equal(location.Source, 'OPS/Text/b chapter.xhtml');
  assert.equal(location.Type, 'KoboSpan');
  assert.equal(await koboCFI(book, location), 'epubcfi(/6/4!/4/2/10/2/1:0)');
  assert.ok(await koboLocation(book, 'epubcfi(/6/4!/4/2/6/1:4)'), 'ordinary text maps to a span in the generated rendition');
  assert.equal(await koboCFI(book, { Source: '../../outside.xhtml', Type: 'KoboSpan', Value: 'kobo.1.1' }), null);
});
